CREATE OR REPLACE FUNCTION fn_scholarship_eligible(
    p_age INTEGER, p_income NUMERIC, p_mark NUMERIC
) RETURNS BOOLEAN LANGUAGE plpgsql AS $$
BEGIN
    IF p_age IS NULL OR p_income IS NULL OR p_mark IS NULL THEN
        RAISE EXCEPTION 'Eligibility inputs cannot be NULL';
    END IF;
    IF p_age <= 0 OR p_income < 0 OR p_mark < 0 OR p_mark > 100 THEN
        RAISE EXCEPTION 'Invalid age, income or mark';
    END IF;
    RETURN p_age BETWEEN 18 AND 25 AND p_income <= 3000 AND p_mark >= 70;
END; $$;

CREATE OR REPLACE PROCEDURE pr_assess_application(p_application_id BIGINT)
LANGUAGE plpgsql AS $$
DECLARE a RECORD; v_status TEXT;
BEGIN
    SELECT * INTO a FROM applications WHERE application_id = p_application_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown application ID %', p_application_id; END IF;
    IF a.status <> 'PENDING' THEN RAISE EXCEPTION 'Application % has already been assessed', p_application_id; END IF;
    IF fn_scholarship_eligible(a.age_at_application,a.monthly_income,a.average_mark) THEN
        v_status := 'APPROVED';
    ELSE
        v_status := 'REJECTED';
    END IF;
    UPDATE applications SET status = v_status WHERE application_id = p_application_id;
END; $$;

CREATE OR REPLACE FUNCTION trg_decision_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status IS DISTINCT FROM OLD.status THEN
        INSERT INTO decision_audit(application_id,old_status,new_status)
        VALUES (NEW.application_id,OLD.status,NEW.status);
    END IF;
    RETURN NEW;
END; $$;
