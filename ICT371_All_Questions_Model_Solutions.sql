CREATE OR REPLACE FUNCTION fn_water_charge(p_units NUMERIC)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
BEGIN
    IF p_units IS NULL OR p_units < 0 THEN RAISE EXCEPTION 'Units cannot be NULL or negative'; END IF;
    RETURN ROUND(LEAST(p_units,10) * 5 + GREATEST(p_units-10,0) * 8, 2);
END; $$;

CREATE OR REPLACE FUNCTION trg_validate_reading()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.previous_reading IS NULL OR NEW.current_reading IS NULL
       OR NEW.previous_reading < 0 OR NEW.current_reading < NEW.previous_reading THEN
        RAISE EXCEPTION 'Current reading must be >= previous reading and both must be non-negative';
    END IF;
    IF EXTRACT(DAY FROM NEW.reading_month) <> 1 THEN RAISE EXCEPTION 'reading_month must be month-start date'; END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER readings_validate
BEFORE INSERT OR UPDATE ON readings FOR EACH ROW EXECUTE FUNCTION trg_validate_reading();

CREATE OR REPLACE PROCEDURE pr_generate_bill(p_reading_id BIGINT, p_due_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_prev NUMERIC(12,2); v_curr NUMERIC(12,2);
BEGIN
    SELECT previous_reading, current_reading INTO v_prev, v_curr
    FROM readings WHERE reading_id = p_reading_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown reading ID %', p_reading_id; END IF;
    IF EXISTS (SELECT 1 FROM bills WHERE reading_id = p_reading_id) THEN
        RAISE EXCEPTION 'Reading % already has a bill', p_reading_id;
    END IF;
    IF p_due_on IS NULL THEN RAISE EXCEPTION 'Due date is required'; END IF;
    INSERT INTO bills(reading_id, charge, amount_paid, due_on)
    VALUES (p_reading_id, fn_water_charge(v_curr-v_prev), 0, p_due_on);
END; $$;

