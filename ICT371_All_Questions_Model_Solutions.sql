-- QUESTION 1: PHARMACY STOCK AND DAILY SALES
-- =========================================================
CREATE SCHEMA IF NOT EXISTS q1;
SET search_path TO q1, public;

CREATE TABLE medicines (
    medicine_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_name TEXT NOT NULL UNIQUE,
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),
    stock_qty INTEGER NOT NULL CHECK (stock_qty >= 0)
);
CREATE TABLE sales (
    sale_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id BIGINT NOT NULL REFERENCES medicines(medicine_id),
    quantity INTEGER NOT NULL CHECK (quantity > 0),
    unit_price NUMERIC(10,2) NOT NULL CHECK (unit_price > 0),
    sold_on DATE NOT NULL
);
CREATE TABLE stock_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    medicine_id BIGINT NOT NULL REFERENCES medicines(medicine_id),
    old_qty INTEGER NOT NULL,
    new_qty INTEGER NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE daily_sales (
    sales_date DATE PRIMARY KEY,
    total_qty BIGINT NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL
);

CREATE OR REPLACE FUNCTION fn_sale_value(p_medicine_id BIGINT, p_quantity INTEGER)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
DECLARE v_price NUMERIC(10,2);
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE EXCEPTION 'Quantity must be positive';
    END IF;
    SELECT unit_price INTO v_price FROM medicines WHERE medicine_id = p_medicine_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown medicine ID %', p_medicine_id; END IF;
    RETURN v_price * p_quantity;
END; $$;

CREATE OR REPLACE PROCEDURE pr_record_sale(
    p_medicine_id BIGINT, p_quantity INTEGER, p_sold_on DATE
) LANGUAGE plpgsql AS $$
DECLARE v_price NUMERIC(10,2); v_stock INTEGER;
BEGIN
    IF p_quantity IS NULL OR p_quantity <= 0 OR p_sold_on IS NULL THEN
        RAISE EXCEPTION 'Quantity must be positive and sale date is required';
    END IF;
    SELECT unit_price, stock_qty INTO v_price, v_stock
    FROM medicines WHERE medicine_id = p_medicine_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown medicine ID %', p_medicine_id; END IF;
    IF v_stock < p_quantity THEN
        RAISE EXCEPTION 'Insufficient stock: available %, requested %', v_stock, p_quantity;
    END IF;
    INSERT INTO sales(medicine_id, quantity, unit_price, sold_on)
    VALUES (p_medicine_id, p_quantity, v_price, p_sold_on);
    UPDATE medicines SET stock_qty = stock_qty - p_quantity
    WHERE medicine_id = p_medicine_id;
END; $$;

CREATE OR REPLACE FUNCTION trg_stock_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.stock_qty IS DISTINCT FROM OLD.stock_qty THEN
        INSERT INTO stock_audit(medicine_id, old_qty, new_qty)
        VALUES (NEW.medicine_id, OLD.stock_qty, NEW.stock_qty);
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER medicines_stock_audit
AFTER UPDATE ON medicines FOR EACH ROW EXECUTE FUNCTION trg_stock_audit();

CREATE OR REPLACE VIEW v_low_stock AS
SELECT medicine_id, medicine_name, unit_price, stock_qty AS remaining_stock
FROM medicines WHERE stock_qty < 10;

CREATE INDEX idx_sales_medicine_sold_on ON sales(medicine_id, sold_on);
-- Index rationale: equality on medicine_id followed by a date range on sold_on.
EXPLAIN SELECT sale_id, quantity, unit_price, sold_on FROM sales
WHERE medicine_id = 1 AND sold_on BETWEEN CURRENT_DATE - 30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_refresh_sales(p_day DATE)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO daily_sales(sales_date, total_qty, total_amount)
    SELECT p_day, COALESCE(SUM(quantity),0), COALESCE(SUM(quantity * unit_price),0)
    FROM sales WHERE sold_on = p_day
    ON CONFLICT (sales_date) DO UPDATE
    SET total_qty = EXCLUDED.total_qty, total_amount = EXCLUDED.total_amount;
END; $$;

