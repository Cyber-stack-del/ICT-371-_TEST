    amount NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    paid_on DATE NOT NULL
);
CREATE TABLE payment_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id BIGINT NOT NULL REFERENCES payments(payment_id),
    student_id BIGINT NOT NULL REFERENCES students(student_id),
    amount NUMERIC(12,2) NOT NULL,
    logged_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE daily_collections (
    collection_date DATE PRIMARY KEY,
    payment_count BIGINT NOT NULL,
    total_amount NUMERIC(12,2) NOT NULL
);

CREATE OR REPLACE FUNCTION fn_fee_balance(p_student_id BIGINT)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
DECLARE v_due NUMERIC(12,2); v_paid NUMERIC(12,2);
BEGIN
    SELECT fee_due INTO v_due FROM students WHERE student_id = p_student_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown student ID %', p_student_id; END IF;
    SELECT COALESCE(SUM(amount),0) INTO v_paid FROM payments WHERE student_id = p_student_id;
    RETURN v_due - v_paid;
END; $$;

CREATE OR REPLACE PROCEDURE pr_receive_payment(
    p_student_id BIGINT, p_amount NUMERIC(12,2), p_paid_on DATE
) LANGUAGE plpgsql AS $$
DECLARE v_due NUMERIC(12,2); v_paid NUMERIC(12,2);
BEGIN
    IF p_amount IS NULL OR p_amount <= 0 OR p_paid_on IS NULL THEN
        RAISE EXCEPTION 'Payment amount must be positive and date is required';
    END IF;
    SELECT fee_due INTO v_due FROM students WHERE student_id = p_student_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown student ID %', p_student_id; END IF;
    SELECT COALESCE(SUM(amount),0) INTO v_paid FROM payments WHERE student_id = p_student_id;
    IF p_amount > v_due - v_paid THEN RAISE EXCEPTION 'Payment exceeds outstanding balance'; END IF;
    INSERT INTO payments(student_id, amount, paid_on) VALUES (p_student_id, p_amount, p_paid_on);
END; $$;

CREATE OR REPLACE FUNCTION trg_payment_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO payment_audit(payment_id, student_id, amount)
    VALUES (NEW.payment_id, NEW.student_id, NEW.amount);
    RETURN NEW;
END; $$;
CREATE TRIGGER payments_audit_after_insert
AFTER INSERT ON payments FOR EACH ROW EXECUTE FUNCTION trg_payment_audit();

CREATE OR REPLACE VIEW v_fee_balances AS
SELECT s.student_number, s.full_name, fn_fee_balance(s.student_id) AS outstanding_balance
FROM students s WHERE fn_fee_balance(s.student_id) > 0;

CREATE INDEX idx_payments_student_paid_on ON payments(student_id, paid_on);
EXPLAIN SELECT payment_id, amount, paid_on FROM payments
WHERE student_id = 1 AND paid_on BETWEEN CURRENT_DATE - 30 AND CURRENT_DATE;

CREATE OR REPLACE PROCEDURE pr_refresh_collections(p_day DATE)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO daily_collections(collection_date, payment_count, total_amount)
    SELECT p_day, COUNT(*), COALESCE(SUM(amount),0)
    FROM payments WHERE paid_on = p_day
    ON CONFLICT (collection_date) DO UPDATE
    SET payment_count = EXCLUDED.payment_count, total_amount = EXCLUDED.total_amount;
END; $$;

