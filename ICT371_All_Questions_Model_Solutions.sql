CREATE OR REPLACE FUNCTION fn_net_pay(p_employee_id BIGINT)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
DECLARE v_basic NUMERIC(12,2); v_allow NUMERIC(12,2); v_ded NUMERIC(12,2); v_net NUMERIC(12,2);
BEGIN
    SELECT basic_salary, allowance, deduction INTO v_basic, v_allow, v_ded
    FROM employees WHERE employee_id = p_employee_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown employee ID %', p_employee_id; END IF;
    v_net := v_basic + v_allow - v_ded;
    IF v_net < 0 THEN RAISE EXCEPTION 'Computed net pay cannot be negative for employee %', p_employee_id; END IF;
    RETURN v_net;
END; $$;

CREATE OR REPLACE PROCEDURE pr_process_payroll(p_month DATE)
LANGUAGE plpgsql AS $$
DECLARE e RECORD; v_net NUMERIC(12,2); v_gross NUMERIC(12,2);
BEGIN
    IF p_month IS NULL OR EXTRACT(DAY FROM p_month) <> 1 THEN
        RAISE EXCEPTION 'Pay month must be the first day of a month';
    END IF;
    FOR e IN SELECT employee_id, basic_salary, allowance FROM employees WHERE active = TRUE LOOP
        v_net := fn_net_pay(e.employee_id);
        v_gross := e.basic_salary + e.allowance;
        INSERT INTO payroll(employee_id, pay_month, gross_pay, net_pay)
        VALUES (e.employee_id, p_month, v_gross, v_net)
        ON CONFLICT (employee_id, pay_month) DO NOTHING;
    END LOOP;
END; $$;

CREATE OR REPLACE FUNCTION trg_salary_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
