-- QUESTION 5: HOSTEL ROOM ALLOCATION
-- =========================================================
CREATE SCHEMA IF NOT EXISTS q5;
SET search_path TO q5, public;

CREATE TABLE students (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_number TEXT NOT NULL UNIQUE,
    full_name TEXT NOT NULL
);
CREATE TABLE rooms (
    room_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_number TEXT NOT NULL UNIQUE,
    capacity INTEGER NOT NULL CHECK (capacity > 0)
);
CREATE TABLE allocations (
    allocation_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(student_id),
    room_id BIGINT NOT NULL REFERENCES rooms(room_id),
    allocated_on DATE NOT NULL,
    released_on DATE,
    status TEXT NOT NULL CHECK (status IN ('ACTIVE','ENDED')),
    CHECK ((status = 'ACTIVE' AND released_on IS NULL) OR (status = 'ENDED' AND released_on IS NOT NULL))
);
CREATE TABLE occupancy_snapshot (
    snapshot_date DATE NOT NULL,
    room_id BIGINT NOT NULL REFERENCES rooms(room_id),
    occupied_beds INTEGER NOT NULL,
    free_beds INTEGER NOT NULL,
    PRIMARY KEY(snapshot_date, room_id)
);

CREATE OR REPLACE FUNCTION fn_free_beds(p_room_id BIGINT)
RETURNS INTEGER LANGUAGE plpgsql AS $$
DECLARE v_capacity INTEGER; v_occupied INTEGER;
BEGIN
    SELECT capacity INTO v_capacity FROM rooms WHERE room_id = p_room_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room ID %', p_room_id; END IF;
    SELECT COUNT(*) INTO v_occupied FROM allocations WHERE room_id = p_room_id AND status = 'ACTIVE';
    RETURN v_capacity - v_occupied;
END; $$;

CREATE OR REPLACE FUNCTION trg_check_allocation()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE v_capacity INTEGER; v_occupied INTEGER;
BEGIN
    IF NEW.status = 'ACTIVE' THEN
        IF EXISTS (SELECT 1 FROM allocations a WHERE a.student_id = NEW.student_id
                   AND a.status = 'ACTIVE' AND a.allocation_id <> COALESCE(NEW.allocation_id,-1)) THEN
            RAISE EXCEPTION 'Student already has an ACTIVE allocation';
        END IF;
        SELECT capacity INTO v_capacity FROM rooms WHERE room_id = NEW.room_id;
        IF NOT FOUND THEN RAISE EXCEPTION 'Unknown room ID %', NEW.room_id; END IF;
        SELECT COUNT(*) INTO v_occupied FROM allocations a
        WHERE a.room_id = NEW.room_id AND a.status = 'ACTIVE'
          AND a.allocation_id <> COALESCE(NEW.allocation_id,-1);
        IF v_occupied >= v_capacity THEN RAISE EXCEPTION 'Room is at capacity'; END IF;
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER allocations_validate
BEFORE INSERT OR UPDATE ON allocations FOR EACH ROW EXECUTE FUNCTION trg_check_allocation();

CREATE OR REPLACE PROCEDURE pr_allocate_room(p_student_id BIGINT, p_room_id BIGINT, p_allocated_on DATE)
LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM students WHERE student_id = p_student_id) THEN
        RAISE EXCEPTION 'Unknown student ID %', p_student_id;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM rooms WHERE room_id = p_room_id) THEN
        RAISE EXCEPTION 'Unknown room ID %', p_room_id;
    END IF;
    IF p_allocated_on IS NULL THEN RAISE EXCEPTION 'Allocation date is required'; END IF;
    IF EXISTS (SELECT 1 FROM allocations WHERE student_id = p_student_id AND status = 'ACTIVE') THEN
        RAISE EXCEPTION 'Student already has an ACTIVE allocation';
    END IF;
    IF fn_free_beds(p_room_id) <= 0 THEN RAISE EXCEPTION 'Room has no free beds'; END IF;
    INSERT INTO allocations(student_id, room_id, allocated_on, released_on, status)
    VALUES (p_student_id, p_room_id, p_allocated_on, NULL, 'ACTIVE');
END; $$;

CREATE OR REPLACE VIEW v_room_occupancy AS
SELECT r.room_id, r.room_number, r.capacity,
       COUNT(a.allocation_id) FILTER (WHERE a.status = 'ACTIVE')::INTEGER AS occupied_beds,
       r.capacity - COUNT(a.allocation_id) FILTER (WHERE a.status = 'ACTIVE')::INTEGER AS free_beds
FROM rooms r LEFT JOIN allocations a ON a.room_id = r.room_id
GROUP BY r.room_id, r.room_number, r.capacity;

CREATE INDEX idx_allocations_active_room ON allocations(room_id) WHERE status = 'ACTIVE';
EXPLAIN SELECT allocation_id, student_id FROM allocations
WHERE room_id = 1 AND status = 'ACTIVE';

CREATE OR REPLACE PROCEDURE pr_refresh_occupancy()
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO occupancy_snapshot(snapshot_date, room_id, occupied_beds, free_beds)
