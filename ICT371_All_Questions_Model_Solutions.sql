CREATE SCHEMA IF NOT EXISTS q3;
SET search_path TO q3, public;

CREATE TABLE books (
    book_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL
);
CREATE TABLE loans (
    loan_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES books(book_id),
    borrower_name TEXT NOT NULL,
    borrowed_on DATE NOT NULL,
    due_on DATE NOT NULL,
    returned_on DATE,
    fine_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (fine_amount >= 0),
    CHECK (due_on >= borrowed_on),
    CHECK (returned_on IS NULL OR returned_on >= borrowed_on)
);
CREATE TABLE loan_audit (
    audit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    loan_id BIGINT NOT NULL REFERENCES loans(loan_id),
    old_returned_on DATE,
    new_returned_on DATE,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE overdue_summary (
    snapshot_date DATE PRIMARY KEY,
    overdue_count BIGINT NOT NULL,
    total_fine NUMERIC(12,2) NOT NULL
);

CREATE OR REPLACE FUNCTION fn_loan_fine(p_loan_id BIGINT, p_as_of DATE)
RETURNS NUMERIC(12,2) LANGUAGE plpgsql AS $$
DECLARE v_due DATE; v_returned DATE; v_end DATE;
BEGIN
    SELECT due_on, returned_on INTO v_due, v_returned FROM loans WHERE loan_id = p_loan_id;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %', p_loan_id; END IF;
    IF p_as_of IS NULL THEN RAISE EXCEPTION 'As-of date is required'; END IF;
    v_end := LEAST(p_as_of, COALESCE(v_returned, p_as_of));
    RETURN GREATEST(v_end - v_due, 0) * 2.00;
END; $$;

CREATE OR REPLACE PROCEDURE pr_return_loan(p_loan_id BIGINT, p_returned_on DATE)
LANGUAGE plpgsql AS $$
DECLARE v_borrowed DATE; v_due DATE; v_returned DATE; v_fine NUMERIC(12,2);
BEGIN
    SELECT borrowed_on, due_on, returned_on INTO v_borrowed, v_due, v_returned
    FROM loans WHERE loan_id = p_loan_id FOR UPDATE;
    IF NOT FOUND THEN RAISE EXCEPTION 'Unknown loan ID %', p_loan_id; END IF;
    IF v_returned IS NOT NULL THEN RAISE EXCEPTION 'Loan % has already been returned', p_loan_id; END IF;
    IF p_returned_on IS NULL OR p_returned_on < v_borrowed THEN
        RAISE EXCEPTION 'Return date must not be before borrowed date';
    END IF;
    v_fine := GREATEST(p_returned_on - v_due, 0) * 2.00;
    UPDATE loans SET returned_on = p_returned_on, fine_amount = v_fine WHERE loan_id = p_loan_id;
END; $$;

CREATE OR REPLACE FUNCTION trg_loan_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.returned_on IS DISTINCT FROM OLD.returned_on THEN
        INSERT INTO loan_audit(loan_id, old_returned_on, new_returned_on)
        VALUES (NEW.loan_id, OLD.returned_on, NEW.returned_on);
    END IF;
    RETURN NEW;
END; $$;
CREATE TRIGGER loans_return_audit
AFTER UPDATE ON loans FOR EACH ROW EXECUTE FUNCTION trg_loan_audit();

CREATE OR REPLACE VIEW v_overdue_loans AS
SELECT b.title, l.borrower_name, l.due_on, fn_loan_fine(l.loan_id, CURRENT_DATE) AS fine_as_of_today
FROM loans l JOIN books b ON b.book_id = l.book_id
WHERE l.returned_on IS NULL AND l.due_on < CURRENT_DATE;

CREATE INDEX idx_loans_book_open_due ON loans(book_id, due_on) WHERE returned_on IS NULL;
EXPLAIN SELECT loan_id, borrower_name, due_on FROM loans
WHERE book_id = 1 AND returned_on IS NULL;

CREATE OR REPLACE PROCEDURE pr_refresh_overdue(p_as_of DATE)
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO overdue_summary(snapshot_date, overdue_count, total_fine)
    SELECT p_as_of, COUNT(*) FILTER (WHERE returned_on IS NULL AND due_on < p_as_of),
           COALESCE(SUM(GREATEST(p_as_of - due_on,0) * 2.00)
             FILTER (WHERE returned_on IS NULL AND due_on < p_as_of),0)
    FROM loans
    ON CONFLICT (snapshot_date) DO UPDATE
    SET overdue_count = EXCLUDED.overdue_count, total_fine = EXCLUDED.total_fine;
END; $$;

